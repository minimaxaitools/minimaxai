#!/usr/bin/env node
/**
 * build-wrappers.js — regenerate the .js wrappers after editing JSON, maps or assets.
 * The studio prefers the real files when served over http; the wrappers make index.html
 * and the Index.html bridge work from file:// too (browsers block fetch() there).
 *
 *   node build-wrappers.js
 *
 * Generates:
 *   presets.motion.js      ← presets.motion.json
 *   content.sample.js      ← content.sample.json
 *   content.hindi.js       ← content.hindi.json (if present)
 *   presets/packs.js       ← presets/*.json (preset packs)
 *   geo/geo-data.js        ← geo/world.json, countries.json, cities.json, regions/*.json
 *   assets/assets.manifest.js ← every file in assets/ (+ keywords from assets/assets.json);
 *                               SVG text is inlined so vector parts stay animatable offline.
 */
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const write = (f, s) => { fs.writeFileSync(path.join(dir, f), s); console.log('→ ' + f); };

[['presets.motion.json', 'presets.motion.js', 'KineticPresets'],
 ['content.sample.json', 'content.sample.js', 'KineticSampleContent'],
 ['content.hindi.json', 'content.hindi.js', 'KineticHindiSample']].forEach(([src, out, global]) => {
    const p = path.join(dir, src);
    if (!fs.existsSync(p)) return;
    const json = JSON.parse(fs.readFileSync(p, 'utf8'));
    write(out, `/* Generated from ${src} by build-wrappers.js — edit the JSON, then run: node build-wrappers.js */\nwindow.${global} = ${JSON.stringify(json, null, 2)};\n`);
});

// preset packs: every presets/*.json becomes part of presets/packs.js (auto-loaded by the Studio and the bridge)
const pDir = path.join(dir, 'presets');
if (fs.existsSync(pDir)) {
    const packs = fs.readdirSync(pDir).filter(f => f.endsWith('.json')).sort().map(f => {
        const j = JSON.parse(fs.readFileSync(path.join(pDir, f), 'utf8'));
        j.pack = Object.assign({ name: f.replace(/\.json$/, '') }, j.pack || {});
        return j;
    });
    write('presets/packs.js', `/* Generated by build-wrappers.js from presets/*.json — preset packs merged over presets.motion.json. */\nwindow.KineticPresetPacks = ${JSON.stringify(packs, null, 1)};\n`);
}

// maps
const geoDir = path.join(dir, 'geo');
if (fs.existsSync(path.join(geoDir, 'world.json'))) {
    const rd = f => JSON.parse(fs.readFileSync(path.join(geoDir, f), 'utf8'));
    const regions = {};
    const rdir = path.join(geoDir, 'regions');
    if (fs.existsSync(rdir)) fs.readdirSync(rdir).filter(f => f.endsWith('.json')).forEach(f => { regions[f.replace(/\.json$/, '')] = rd('regions/' + f); });
    write('geo/geo-data.js', `/* Generated by build-wrappers.js. Map data: amCharts 5 geodata (linkware — keep the attribution), GeoNames (CC BY 4.0), i18n-iso-countries. */\nwindow.KineticGeoData = ${JSON.stringify({ world: rd('world.json'), countries: rd('countries.json'), cities: rd('cities.json'), regions })};\n`);
}

// assets
const aDir = path.join(dir, 'assets');
if (fs.existsSync(aDir)) {
    let meta = [];
    try { meta = JSON.parse(fs.readFileSync(path.join(aDir, 'assets.json'), 'utf8')); } catch (e) { /* optional */ }
    const byFile = new Map(meta.map(m => [m.file, m]));
    const list = fs.readdirSync(aDir).filter(f => /\.(svg|png|jpe?g|webp|gif|mp3|wav|ogg|m4a)$/i.test(f)).map(f => {
        const m = byFile.get(f) || {};
        const a = { name: m.name || f.replace(/\.[^.]+$/, ''), keywords: m.keywords || [], src: 'assets/' + f };
        if (/\.svg$/i.test(f)) { a.type = 'svg'; a.svg = fs.readFileSync(path.join(aDir, f), 'utf8'); }
        else if (/\.(mp3|wav|ogg|m4a)$/i.test(f)) a.type = 'audio';
        else a.type = 'image';
        return a;
    });
    write('assets/assets.manifest.js', `/* Generated by build-wrappers.js from the assets/ folder. Add files there (optionally keywords in assets.json) and re-run. */\nwindow.KineticAssets = ${JSON.stringify(list, null, 1)};\n`);
}
